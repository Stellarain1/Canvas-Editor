#pragma once
#include "ScoreSerializer.h"
#include "Canvas/Core/Version.h"

namespace MikuMikuWorld
{
    class Note;
    class SUSNote;
    class SUS;

    class SusSerializer : public ScoreSerializer
    {
        std::string exportComment;
        bool includeNoteSpeed{ true };
        // true: fold every hi-speed layer onto #TIL00 like the game reads it.
        // false: keep layers as #TILxx + #HISPEED switches (MMW4CC-style).
        bool mergeLayers{ true };

        std::pair<int, int> barLengthToFraction(float length, float fractionDenom);
        std::string noteKey(const SUSNote& note);
        std::string noteKey(const Note& note);

        Score susToScore(const SUS& sus);
        SUS scoreToSus(const Score& score);

    public:
        explicit SusSerializer(bool includeNoteSpeed = true, bool mergeLayers = true)
            : includeNoteSpeed{ includeNoteSpeed }, mergeLayers{ mergeLayers }
        {
            exportComment = "This file was generated by " + Canvas::generatorString();
        }

        void serialize(const Score& score, std::string filename) override;
        Score deserialize(std::string filename) override;
    };
}
